import {chromePath} from './browser-runtime.mjs';
import { chromium } from '../frontend/node_modules/playwright-core/index.mjs';
import fs from 'node:fs';
const browser=await chromium.launch({executablePath:chromePath(),headless:true,args:['--autoplay-policy=no-user-gesture-required']});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://127.0.0.1:8765');
await page.waitForTimeout(5000);
const display=page.frameLocator('iframe');
await display.getByRole('button',{name:'启用声音与角色'}).click({timeout:20000});
await page.waitForTimeout(2000);
const state=await page.evaluate(async()=>await (await fetch('/api/state')).json());
console.log(JSON.stringify({connected:state.player_connected,errors,state:{stopped:state.stopped}},null,2));
fs.mkdirSync('docs/screenshots',{recursive:true});
await display.locator('.display').screenshot({path:'docs/screenshots/yier-bubu-stage.png'});
await page.screenshot({path:'docs/screenshots/studio-desktop.png',fullPage:true});
await page.getByRole('button',{name:'风控与运行',exact:true}).click();
await page.screenshot({path:'docs/screenshots/safety-desktop.png',fullPage:true});
await page.getByRole('button',{name:'导播台',exact:true}).click();
await page.getByRole('button',{name:'停止发声与清空队列'}).click();
const paused=await page.evaluate(async()=>await (await fetch('/api/state')).json());
if(!paused.stopped)throw Error('Emergency stop failed');
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(1000);
await page.screenshot({path:'docs/screenshots/studio-mobile.png',fullPage:true});
await browser.close();
if(errors.length)process.exitCode=1;
