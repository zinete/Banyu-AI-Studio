import {build} from '../frontend/node_modules/esbuild/lib/main.js';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const result=await build({absWorkingDir:path.resolve('frontend'),entryPoints:['./src/bears.ts'],bundle:true,platform:'node',format:'esm',write:false});
fs.writeFileSync('.runtime/bear-rig-bundle.mjs',result.outputFiles[0].text);
const {buildBear,animateBear}=await import('../.runtime/bear-rig-bundle.mjs');
const yier=buildBear('yier'),bubu=buildBear('bubu');
animateBear(yier,'yier',1,.8,'wave',false,false);
animateBear(bubu,'bubu',1,.8,'wave',false,false);
assert.equal(yier.mouth.visible,true);
assert.equal(bubu.mouth.visible,false);
assert.ok(yier.leftArm.rotation.z < -1);
assert.ok(bubu.rightArm.rotation.z > 1);
animateBear(yier,'yier',2,.8,'smile',false,false);
assert.equal(yier.happyEyes.visible,true);
animateBear(yier,'yier',3,.8,'confused',false,false);
assert.ok(yier.head.rotation.z < -.1);
animateBear(yier,'yier',3,.8,'wave',true,false);
assert.equal(yier.mouth.visible,false);
assert.equal(yier.root.userData.mouthLevel,0);
const stopped={head:yier.head.rotation.toArray(),arm:yier.leftArm.rotation.toArray(),y:yier.root.position.y};
animateBear(yier,'yier',6,.9,'wave',true,false);
assert.deepEqual({head:yier.head.rotation.toArray(),arm:yier.leftArm.rotation.toArray(),y:yier.root.position.y},stopped);
animateBear(yier,'yier',3,.8,'wave',false,true);
assert.equal(yier.leftArm.rotation.z,-.18);
assert.equal(yier.mouth.visible,true);
const checks={mouth_follows_audio:true,bubu_does_not_lipsync:true,wave:true,smile:true,confused:true,stop_freezes_pose:true,reduced_motion:true};
fs.writeFileSync('docs/verification/bear-rig.json',JSON.stringify(checks,null,2));
console.log(JSON.stringify(checks));
